    @staticmethod
    def realtor_saved_ask_client_fio(realtor_fio: str, agency: str) -> str:
        short_fio = format_short_fio(realtor_fio)
        if not agency or agency.lower() == "нет":
            agency_part = "(частный агент)"
        else:
            agency_part = f'из агентства "{agency}"'
        
